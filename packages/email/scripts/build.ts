import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { svelte } from "@sveltejs/vite-plugin-svelte";
import { pixelBasedPreset, Renderer, toPlainText } from "@better-svelte-email/server";
import { createServer } from "vite";
import { emailTailwindConfig } from "../src/lib/email-theme.ts";
import { TEMPLATES } from "../src/templates.ts";

// Renders each template once with {{tokens}} so the server needs no Svelte or Tailwind at runtime.
const root = fileURLToPath(new URL("..", import.meta.url));
const out = new URL("../src/generated.js", import.meta.url);

const vite = await createServer({
	root,
	mode: "production",
	plugins: [svelte({ compilerOptions: { dev: false } })],
	ssr: { noExternal: [/@better-svelte-email/] },
	server: { middlewareMode: true },
	appType: "custom",
	logLevel: "error"
});
try {
	const { default: Action } = await vite.ssrLoadModule("/src/templates/ActionEmail.svelte");
	const renderer = new Renderer({
		tailwindConfig: { ...emailTailwindConfig, presets: [pixelBasedPreset] }
	});
	const rendered: Record<string, { html: string; text: string }> = {};
	for (const [name, t] of Object.entries(TEMPLATES)) {
		const props = {
			preview: t.preview,
			eyebrow: t.eyebrow,
			heading: t.heading,
			lines: t.lines,
			actionLabel: t.action,
			actionUrl: "{{url}}"
		};
		const html = await renderer.render(Action, { props });
		rendered[name] = {
			html,
			text: `${t.heading}

${toPlainText(html)}`
		};
	}
	const source = `// Generated by scripts/build.ts. Do not edit.\nexport const generated = ${JSON.stringify(rendered, null, "\t")};\n`;
	if (process.argv.includes("--check")) {
		if (readFileSync(out, "utf8") !== source) {
			console.error("src/generated.js is stale. Run pnpm --filter @glyphtex/email build.");
			process.exitCode = 1;
		}
	} else writeFileSync(out, source);
} finally {
	await vite.close();
}
